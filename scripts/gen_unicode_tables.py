"""Generate the Rust character-class tables used by the Rust pre-tokenizer.

The Python pre-tokenizer relies on the standard-library ``re`` module, whose
``\\s``, ``\\d``, and ``\\w`` classes follow the Unicode database bundled with
the running interpreter, and that database changes between Python releases. To
make the Rust pre-tokenizer agree with ``re`` on every code point, this script
asks ``re`` itself how each code point is classified and writes the result as
sorted ranges, one table per Unicode version. Run it once with every supported
interpreter:

    for v in 3.12 3.13 3.14 3.15; do
        uv run --no-project --python "$v" python scripts/gen_unicode_tables.py
    done

Each run writes ``rust/src/unicode_tables/u<version>.rs`` and regenerates
``rust/src/unicode_tables/mod.rs`` from the tables present. At runtime the
Python package passes ``unicodedata.unidata_version`` to the extension, which
selects the matching table or reports that it has none.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

OUTPUT_DIR = Path(__file__).resolve().parent.parent / "rust" / "src" / "unicode_tables"

# The character classes used by the alternatives of the pre-tokenization pattern.
_CLASSES = (
    ("Space", re.compile(r"\s")),
    ("Letter", re.compile(r"[^\W\d_]")),
    ("Digit", re.compile(r"\d")),
    ("Other", re.compile(r"(?:[^\s\w]|_)")),
)

HEADER = "// @generated by scripts/gen_unicode_tables.py; do not edit by hand.\n"


def classify(codepoint: int) -> str:
    char = chr(codepoint)
    matches = [name for name, pattern in _CLASSES if pattern.fullmatch(char)]
    if len(matches) != 1:
        raise SystemExit(f"U+{codepoint:04X} matched {matches}; classes must partition")
    return matches[0]


def ranges() -> list[tuple[int, int, str]]:
    out: list[tuple[int, int, str]] = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        name = classify(codepoint)
        if name == "Other":
            continue
        if out and out[-1][2] == name and out[-1][1] == codepoint - 1:
            out[-1] = (out[-1][0], codepoint, name)
        else:
            out.append((codepoint, codepoint, name))
    return out


def module_name(version: str) -> str:
    return "u" + version.replace(".", "_")


def render_table(version: str, table: list[tuple[int, int, str]]) -> str:
    lines = [
        HEADER.rstrip("\n"),
        "//",
        f"// Character classes of Python's `re` module under Unicode {version}",
        "// (`\\s`, `[^\\W\\d_]`, `\\d`) for every Unicode scalar value. Code points",
        "// not listed are `Other`.",
        "",
        "use crate::pretokenize::CharClass;",
        "",
        f"pub static CLASS_RANGES: [(u32, u32, CharClass); {len(table)}] = [",
    ]
    lines.extend(f"    (0x{lo:X}, 0x{hi:X}, CharClass::{name})," for lo, hi, name in table)
    lines.append("];")
    return "\n".join(lines) + "\n"


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def render_mod(versions: list[str]) -> str:
    versions = sorted(versions, key=version_key)
    lines = [
        HEADER.rstrip("\n"),
        "",
        "//! Character-class tables, one per Unicode version of the Python `re` module.",
        "",
        "use crate::pretokenize::CharClass;",
        "",
    ]
    lines.extend(f"mod {module_name(v)};" for v in versions)
    lines += [
        "",
        "/// A sorted list of `(first, last, class)` code point ranges.",
        "pub type ClassTable = &'static [(u32, u32, CharClass)];",
        "",
        "/// Every supported Unicode version with its table, oldest first.",
        "pub static TABLES: &[(&str, ClassTable)] = &[",
    ]
    lines.extend(f'    ("{v}", &{module_name(v)}::CLASS_RANGES),' for v in versions)
    lines += [
        "];",
        "",
        "/// The newest supported Unicode version, used when none is requested.",
        f'pub const UNICODE_VERSION: &str = "{versions[-1]}";',
        "",
        "/// Return the table for `version`, or `None` if it is not supported.",
        "pub fn table_for(version: &str) -> Option<ClassTable> {",
        "    TABLES",
        "        .iter()",
        "        .find(|(v, _)| *v == version)",
        "        .map(|&(_, table)| table)",
        "}",
        "",
        "/// The table for [`UNICODE_VERSION`].",
        "pub fn default_table() -> ClassTable {",
        "    TABLES[TABLES.len() - 1].1",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    version = unicodedata.unidata_version
    path = OUTPUT_DIR / f"{module_name(version)}.rs"
    path.write_text(render_table(version, ranges()), encoding="utf-8")
    versions = sorted(
        p.stem[1:].replace("_", ".") for p in OUTPUT_DIR.glob("u*.rs") if p.stem != "mod"
    )
    (OUTPUT_DIR / "mod.rs").write_text(render_mod(versions), encoding="utf-8")
    sys.stdout.write(f"wrote {path} (Unicode {version}); tables: {', '.join(versions)}\n")


if __name__ == "__main__":
    main()
